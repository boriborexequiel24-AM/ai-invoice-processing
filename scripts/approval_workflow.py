"""n8n workflow 2: "Approval + Xero".

Slack calls this workflow when someone clicks Approve or Reject on an invoice
message. It:
  1. Checks the request really came from Slack (signature + timestamp).
  2. Records the decision, only if the invoice is still open.
  3. For approved invoices (not public demo uploads): creates a bill in the
     Xero demo company and attaches the PDF.
  4. Replaces the buttons in Slack with the outcome.

Built and deployed by scripts/build_n8n_workflow.py.
"""

from __future__ import annotations

import json
from pathlib import Path

from build_n8n_workflow import (
    BUCKET,
    ROOT,
    SLACK_BLOCKS_JS,
    if_node,
    node,
    node_id,
    slack_request,
    supabase_request,
)

OUTPUT = ROOT / "n8n" / "workflows" / "invoice-approval-xero.json"
WORKFLOW_NAME = "Invoice Processing | 2. Approval + Xero"
WEBHOOK_PATH = "invoice-slack-actions"
EXPENSE_ACCOUNT_NAME = "General Expenses"  # used if it exists in Xero, otherwise the first expense account
XERO_BILL_URL = "https://go.xero.com/AccountsPayable/View.aspx?InvoiceID="
OPEN_STATUSES = ["ready_for_approval", "needs_review", "flagged"]


def config_code(env: dict) -> str:
    settings = {
        "supabase_url": env["SUPABASE_URL"].rstrip("/"),
        "bucket": BUCKET,
        "signing_secret": env["SLACK_SIGNING_SECRET"],
        "alerts_channel": env["SLACK_ALERTS_CHANNEL_ID"],
        "expense_account_name": EXPENSE_ACCOUNT_NAME,
        "xero_bill_url": XERO_BILL_URL,
    }
    return (
        "// Settings for this workflow. Generated by scripts/build_n8n_workflow.py.\n"
        f"return [{{ json: {json.dumps(settings, indent=2)}, binary: $input.first().binary }}];"
    )


READ_REQUEST_CODE = """// Slack signs every request it sends. Rebuild the signed text so the next step can check it.
const request = $('Slack action').first();
const headers = request.json.headers || {};
const timestamp = headers['x-slack-request-timestamp'] || '';
const signature = headers['x-slack-signature'] || '';

const binaryKey = Object.keys($input.first().binary || {})[0];
const raw = binaryKey ? (await this.helpers.getBinaryDataBuffer(0, binaryKey)).toString('utf8') : '';

const payloadText = request.json.body?.payload;
const ageSeconds = Math.abs(Date.now() / 1000 - Number(timestamp));

return [{
  json: {
    base_string: `v0:${timestamp}:${raw}`,
    signature,
    has_raw_body: raw.length > 0,
    fresh: Number.isFinite(ageSeconds) && ageSeconds < 300,  // reject replays older than 5 minutes
    payload: payloadText ? JSON.parse(payloadText) : null,
  },
}];"""


READ_DECISION_CODE = """// Which button was clicked, on which invoice, by whom.
const payload = $json.payload;
const action = payload?.actions?.[0];
if (!action || !['approve_invoice', 'reject_invoice'].includes(action.action_id)) return [];

return [{
  json: {
    decision: action.action_id === 'approve_invoice' ? 'approve' : 'reject',
    invoice_id: action.value,
    user: payload.user?.name || payload.user?.username || payload.user?.id || 'someone',
    user_id: payload.user?.id || null,
    channel: payload.channel?.id || payload.container?.channel_id || null,
    message_ts: payload.message?.ts || payload.container?.message_ts || null,
  },
}];"""


PICK_ORG_CODE = """// The credential may have access to several Xero organisations. Use the Demo Company.
const orgs = $input.all().map(item => item.json).filter(o => o.tenantId);
const org = orgs.find(o => /demo/i.test(o.tenantName || '')) || orgs[0];
if (!org) throw new Error('No Xero organisation is connected to the n8n Xero credential.');
return [{ json: { tenant_id: org.tenantId, tenant_name: org.tenantName } }];"""


BUILD_BILL_CODE = """// Turn the approved invoice into a Xero bill (type ACCPAY).
// Amounts are sent exactly as printed. Tax goes on its own line so the bill total
// matches the invoice without depending on Xero's tax settings.
const config = $('Config').first().json;
const inv = $('Load invoice').first().json;
const accounts = $input.first().json.Accounts || [];
const account = accounts.find(a => a.Name === config.expense_account_name && a.Code) || accounts.find(a => a.Code);
if (!account) throw new Error('No expense account with a code was found in Xero.');

const round = v => Math.round(Number(v) * 100) / 100;
const lines = (inv.invoice_line_items || [])
  .sort((a, b) => a.position - b.position)
  .map(li => {
    const qty = Number(li.quantity ?? 1);
    const unit = li.unit_price === null ? null : Number(li.unit_price);
    const exact = unit !== null && round(qty * unit) === round(li.amount);
    return {
      Description: li.description,
      Quantity: exact ? qty : 1,
      UnitAmount: exact ? unit : Number(li.amount),
      AccountCode: account.Code,
    };
  });
if (!lines.length) {
  lines.push({ Description: 'Invoice total', Quantity: 1, UnitAmount: Number(inv.subtotal ?? inv.total), AccountCode: account.Code });
}
if (Number(inv.tax) > 0) {
  lines.push({ Description: 'Tax (as printed on the invoice)', Quantity: 1, UnitAmount: Number(inv.tax), AccountCode: account.Code });
}

const bill = {
  Type: 'ACCPAY',
  Contact: { Name: inv.vendor_name_raw },
  Date: inv.invoice_date,
  DueDate: inv.due_date,
  InvoiceNumber: inv.invoice_number,
  Reference: inv.po_number || undefined,
  CurrencyCode: inv.currency,
  LineAmountTypes: 'NoTax',
  Status: 'AUTHORISED',
  LineItems: lines,
};
for (const key of Object.keys(bill)) if (bill[key] === null || bill[key] === undefined) delete bill[key];

return [{ json: { body: { Invoices: [bill] }, account_code: account.Code } }];"""


XERO_ERROR_CODE = """// Turn Xero's error response into a short, readable message.
const error = $input.first().json.error ?? {};
const text = typeof error === 'string' ? error : (error.description ?? error.message ?? JSON.stringify(error));
let message = text;
try {
  // HTTP errors look like: 400 - "{ ...json... }" (a JSON string holding Xero's JSON body)
  let body = text.replace(/^\\d{3}\\s*-\\s*/, '');
  if (body.startsWith('"')) body = JSON.parse(body);
  const parsed = JSON.parse(body.slice(body.indexOf('{')));
  const reasons = [];
  for (const element of parsed.Elements || []) {
    for (const v of element.ValidationErrors || []) reasons.push(v.Message);
  }
  message = reasons.length ? [...new Set(reasons)].join(' ') : (parsed.Message || text);
} catch (_) {
  // Not JSON: keep the original text.
}
return [{ json: { message: String(message).slice(0, 500) } }];"""


SLACK_UPDATE_CODE = SLACK_BLOCKS_JS + """
// Replace the buttons with the outcome.
const config = $('Config').first().json;
const d = $('Read decision').first().json;
const inv = { ...$('Load invoice').first().json };
let text;

if (!$('Save decision').isExecuted) {
  text = `:information_source: Already ${inv.status.replace(/_/g, ' ')}${inv.decided_by ? ` by ${inv.decided_by}` : ''}. No change made.`;
} else if (d.decision === 'reject') {
  inv.status = 'rejected';
  text = `:x: Rejected by ${d.user}.`;
} else if ($('Mark posted').isExecuted) {
  inv.status = 'posted';
  const xeroId = $('Create Xero bill').first().json.Invoices[0].InvoiceID;
  text = `:white_check_mark: Approved by ${d.user} and posted to Xero as a bill. <${config.xero_bill_url}${xeroId}|Open in Xero>`;
} else if ($('Log Xero error').isExecuted) {
  inv.status = 'approved';
  text = `:white_check_mark: Approved by ${d.user}, but posting to Xero failed. Details were sent to the alerts channel.`;
} else {
  inv.status = 'approved';
  text = `:white_check_mark: Approved by ${d.user}. This is a demo upload, so it was not posted to Xero.`;
}

return [{
  json: {
    body: {
      channel: d.channel || inv.slack_channel,
      ts: d.message_ts || inv.slack_message_ts,
      text,
      blocks: invoiceBlocks(inv, text),
    },
  },
}];"""


def xero_request(name: str, position, method: str, url: str, *, body: str | None = None,
                 binary_field: str | None = None, tenant: bool = True, **extra) -> dict:
    """HTTP Request node that calls Xero with the generic OAuth2 credential."""
    headers = [{"name": "Accept", "value": "application/json"}]
    if tenant:
        headers.append({"name": "xero-tenant-id", "value": "={{ $('Pick Xero organisation').first().json.tenant_id }}"})
    params = {
        "method": method,
        "url": url,
        "authentication": "genericCredentialType",
        "genericAuthType": "oAuth2Api",
        "sendHeaders": True,
        "headerParameters": {"parameters": headers},
        "options": {"timeout": 60000},
    }
    if body is not None:
        params.update({"sendBody": True, "specifyBody": "json", "jsonBody": body})
    if binary_field:
        headers.append({"name": "Content-Type", "value": "application/pdf"})
        params.update({"sendBody": True, "contentType": "binaryData", "inputDataFieldName": binary_field})
    return node(name, "n8n-nodes-base.httpRequest", 4.2, position, params, **extra)


def build_approval_workflow(env: dict) -> dict:
    y, row_xero, row_err = 300, 520, 740
    x = lambda col: col * 240  # noqa: E731
    open_list = ",".join(OPEN_STATUSES)

    nodes = [
        node("Slack action", "n8n-nodes-base.webhook", 2, (x(0), y), {
            "httpMethod": "POST",
            "path": WEBHOOK_PATH,
            "responseMode": "onReceived",  # Slack needs an answer within 3 seconds
            "options": {"rawBody": True},  # needed to check Slack's signature
        }, webhookId=node_id("slack-webhook")),
        node("Config", "n8n-nodes-base.code", 2, (x(1), y), {"jsCode": config_code(env)}),
        node("Read Slack request", "n8n-nodes-base.code", 2, (x(2), y), {"jsCode": READ_REQUEST_CODE}),
        node("Sign request", "n8n-nodes-base.crypto", 1, (x(3), y), {
            "action": "hmac",
            "type": "SHA256",
            "value": "={{ $json.base_string }}",
            "dataPropertyName": "expected_signature",
            "secret": "={{ $('Config').first().json.signing_secret }}",
            "encoding": "hex",
        }),
        if_node("Genuine Slack request?", (x(4), y),
                "={{ $json.fresh && $json.has_raw_body && ('v0=' + $json.expected_signature) === $json.signature }}",
                {"type": "boolean", "operation": "true", "singleValue": True}),
        node("Read decision", "n8n-nodes-base.code", 2, (x(5), y), {"jsCode": READ_DECISION_CODE}),
        supabase_request(
            "Load invoice", (x(6), y), "GET",
            "/rest/v1/invoices?select=*,invoice_line_items(*)&id=eq.{{ $json.invoice_id }}",
        ),
        if_node("Still open?", (x(7), y),
                "={{ " + json.dumps(OPEN_STATUSES) + ".includes($json.status) }}",
                {"type": "boolean", "operation": "true", "singleValue": True}),
        # The status filter makes a double click (or two people clicking) harmless.
        supabase_request(
            "Save decision", (x(8), y), "PATCH",
            "/rest/v1/invoices?id=eq.{{ $('Read decision').first().json.invoice_id }}&status=in.(" + open_list + ")",
            body="={{ JSON.stringify({ status: $('Read decision').first().json.decision === 'approve' ? 'approved' : 'rejected', "
                 "decided_by: $('Read decision').first().json.user, decided_at: new Date().toISOString() }) }}",
            prefer="return=representation",
        ),
        supabase_request(
            "Log decision", (x(9), y), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify({ invoice_id: $('Read decision').first().json.invoice_id, "
                 "step: $('Read decision').first().json.decision === 'approve' ? 'approved' : 'rejected', "
                 "actor: 'slack:' + $('Read decision').first().json.user, "
                 "details: { slack_user_id: $('Read decision').first().json.user_id } }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        if_node("Send to Xero?", (x(10), y),
                "={{ $('Read decision').first().json.decision === 'approve' && $('Load invoice').first().json.source !== 'upload' }}",
                {"type": "boolean", "operation": "true", "singleValue": True}),

        # Xero branch
        xero_request("Xero organisations", (x(11), row_xero), "GET", "https://api.xero.com/connections",
                     tenant=False, onError="continueErrorOutput"),
        node("Pick Xero organisation", "n8n-nodes-base.code", 2, (x(12), row_xero), {"jsCode": PICK_ORG_CODE},
             onError="continueErrorOutput"),
        xero_request("Find expense account", (x(13), row_xero), "GET",
                     "=https://api.xero.com/api.xro/2.0/Accounts?where="
                     "{{ encodeURIComponent('Type==\"EXPENSE\" && Status==\"ACTIVE\"') }}",
                     onError="continueErrorOutput"),
        node("Build Xero bill", "n8n-nodes-base.code", 2, (x(14), row_xero), {"jsCode": BUILD_BILL_CODE},
             onError="continueErrorOutput"),
        xero_request("Create Xero bill", (x(15), row_xero), "POST", "https://api.xero.com/api.xro/2.0/Invoices",
                     body="={{ JSON.stringify($json.body) }}", onError="continueErrorOutput"),
        node("Download PDF", "n8n-nodes-base.httpRequest", 4.2, (x(16), row_xero), {
            "method": "GET",
            "url": "={{ $('Config').first().json.supabase_url }}/storage/v1/object/"
                   "{{ $('Config').first().json.bucket }}/{{ $('Load invoice').first().json.file_path }}",
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "supabaseApi",
            "options": {"response": {"response": {"responseFormat": "file", "outputPropertyName": "data"}}},
        }, onError="continueRegularOutput"),
        xero_request("Attach PDF to bill", (x(17), row_xero), "PUT",
                     "=https://api.xero.com/api.xro/2.0/Invoices/{{ $('Create Xero bill').first().json.Invoices[0].InvoiceID }}"
                     "/Attachments/{{ encodeURIComponent($('Load invoice').first().json.file_name || 'invoice.pdf') }}",
                     binary_field="data", onError="continueRegularOutput"),
        supabase_request(
            "Mark posted", (x(18), row_xero), "PATCH",
            "/rest/v1/invoices?id=eq.{{ $('Read decision').first().json.invoice_id }}",
            body="={{ JSON.stringify({ status: 'posted', "
                 "xero_bill_id: $('Create Xero bill').first().json.Invoices[0].InvoiceID, "
                 "xero_url: $('Config').first().json.xero_bill_url + $('Create Xero bill').first().json.Invoices[0].InvoiceID }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        supabase_request(
            "Log posted", (x(19), row_xero), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify({ invoice_id: $('Read decision').first().json.invoice_id, step: 'posted', actor: 'system', "
                 "details: { xero_invoice_id: $('Create Xero bill').first().json.Invoices[0].InvoiceID, "
                 "xero_organisation: $('Pick Xero organisation').first().json.tenant_name, "
                 "account_code: $('Build Xero bill').first().json.account_code, "
                 "pdf_attached: !$('Attach PDF to bill').first().json.error } }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),

        # Xero error branch: keep the approval, record the error, tell the team.
        node("Read Xero error", "n8n-nodes-base.code", 2, (x(15), row_err), {"jsCode": XERO_ERROR_CODE}),
        supabase_request(
            "Log Xero error", (x(16), row_err), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify({ invoice_id: $('Read decision').first().json.invoice_id, step: 'error', actor: 'system', "
                 "details: { stage: 'xero', error: $json.message } }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        slack_request("Alert team", (x(17), row_err), "chat.postMessage",
                      "={{ JSON.stringify({ channel: $('Config').first().json.alerts_channel, "
                      "text: ':warning: Invoice ' + ($('Load invoice').first().json.invoice_number || $('Read decision').first().json.invoice_id) "
                      "+ ' was approved but could not be posted to Xero: ' + $('Read Xero error').first().json.message }) }}",
                      executeOnce=True, onError="continueRegularOutput"),

        node("Build Slack update", "n8n-nodes-base.code", 2, (x(20), y), {"jsCode": SLACK_UPDATE_CODE}),
        slack_request("Update Slack message", (x(21), y), "chat.update", "={{ JSON.stringify($json.body) }}",
                      onError="continueRegularOutput"),
    ]

    def link(*names: str) -> dict:
        return {"main": [[{"node": n, "type": "main", "index": 0} for n in names]]}

    def branch(ok: str, err: str) -> dict:
        return {"main": [[{"node": ok, "type": "main", "index": 0}], [{"node": err, "type": "main", "index": 0}]]}

    connections = {
        "Slack action": link("Config"),
        "Config": link("Read Slack request"),
        "Read Slack request": link("Sign request"),
        "Sign request": link("Genuine Slack request?"),
        "Genuine Slack request?": {"main": [[{"node": "Read decision", "type": "main", "index": 0}], []]},
        "Read decision": link("Load invoice"),
        "Load invoice": link("Still open?"),
        "Still open?": branch("Save decision", "Build Slack update"),
        "Save decision": link("Log decision"),
        "Log decision": link("Send to Xero?"),
        "Send to Xero?": branch("Xero organisations", "Build Slack update"),
        "Xero organisations": branch("Pick Xero organisation", "Read Xero error"),
        "Pick Xero organisation": branch("Find expense account", "Read Xero error"),
        "Find expense account": branch("Build Xero bill", "Read Xero error"),
        "Build Xero bill": branch("Create Xero bill", "Read Xero error"),
        "Create Xero bill": branch("Download PDF", "Read Xero error"),
        "Read Xero error": link("Log Xero error"),
        "Download PDF": link("Attach PDF to bill"),
        "Attach PDF to bill": link("Mark posted"),
        "Mark posted": link("Log posted"),
        "Log posted": link("Build Slack update"),
        "Log Xero error": link("Alert team"),
        "Alert team": link("Build Slack update"),
        "Build Slack update": link("Update Slack message"),
    }

    return {
        "name": WORKFLOW_NAME,
        "nodes": nodes,
        "connections": connections,
        "settings": {"executionOrder": "v1"},
    }
