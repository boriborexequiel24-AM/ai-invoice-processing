"""n8n workflow 4: "Email intake".

Every minute, looks for labelled messages carrying a PDF and posts each PDF to
the same intake webhook the dashboard uses, tagged as source=email. Everything
after that (fingerprinting, AI reading, the checks, Slack) is workflow 1, so
email and upload follow exactly the same path.

Why a schedule and not n8n's Gmail Trigger:
    The Gmail Trigger only returns messages that ARRIVED since its last poll.
    Here the label is what queues an invoice, and a label is always applied
    after the message arrives, so the trigger's clock moves past the message
    while it is still unlabelled and it can never be picked up again. A plain
    search has no such window: a message counts as queued for as long as it
    carries the label.

The label is also the dedupe. Once a PDF has been handed over, the label is
removed, so the next run no longer sees it. If the hand-over fails the label
stays on and the message is retried a minute later.

Only labelled messages are read, so nothing else in the mailbox is touched.
Built and deployed by scripts/build_n8n_workflow.py.
"""

from __future__ import annotations

import json

from build_n8n_workflow import ROOT, if_node, node, slack_request

OUTPUT = ROOT / "n8n" / "workflows" / "invoice-email-intake.json"
WORKFLOW_NAME = "Invoice Processing | 4. Email intake"

# The label that queues an invoice. Deliberately not something generic like
# "invoices": anything carrying it is extracted and shown on the public
# dashboard, so it must be a label no existing Gmail filter would ever apply.
LABEL_NAME = "invoice-demo"
GMAIL_QUERY = f"label:{LABEL_NAME} has:attachment"
MAX_PER_RUN = 10

# A repeat of the same file is not a problem: workflow 1 fingerprints every PDF
# and answers 409 without processing it again.
ACCEPTED_CODES = [200, 409]

GMAIL_API = "https://gmail.googleapis.com/gmail/v1/users/me"


def config_code(env: dict) -> str:
    settings = {
        "intake_url": env["N8N_BASE_URL"].rstrip("/") + "/webhook/invoice-intake",
        "webhook_secret": env["N8N_WEBHOOK_SECRET"],
        "alerts_channel": env["SLACK_ALERTS_CHANNEL_ID"],
        "label_name": LABEL_NAME,
    }
    return (
        "// Generated by scripts/build_n8n_workflow.py.\n"
        f"return [{{ json: {json.dumps(settings, indent=2)} }}];"
    )


FIND_LABEL_CODE = """// Gmail needs a label id, not a name, to take a label off a message.
const wanted = $('Config').first().json.label_name.toLowerCase();
const labels = $input.first().json.labels || [];
const match = labels.find(l => String(l.name).toLowerCase() === wanted);
if (!match) {
  throw new Error(`No Gmail label named "${$('Config').first().json.label_name}". Create it, then label an invoice.`);
}
return [{ json: { label_id: match.id } }];"""


PICK_PDFS_CODE = """// One item per PDF attachment, with the file always under the same name,
// so the next step can post it without knowing how many came in.
const out = [];

for (const item of $input.all()) {
  const message = item.json;

  // Gmail returns the sender and subject in a few shapes depending on the
  // node version, so read the raw headers first and fall back from there.
  const headers = {};
  for (const h of message.payload?.headers || []) headers[String(h.name).toLowerCase()] = h.value;
  const from = headers.from ?? message.From ?? message.from?.value?.[0]?.address ?? message.from ?? null;
  const subject = headers.subject ?? message.Subject ?? message.subject ?? null;

  for (const [key, meta] of Object.entries(item.binary || {})) {
    const fileName = meta.fileName || '';
    const isPdf = meta.mimeType === 'application/pdf' || fileName.toLowerCase().endsWith('.pdf');
    if (!isPdf) continue;
    out.push({
      json: {
        file_name: fileName || 'invoice.pdf',
        message_id: message.id,
        subject: typeof subject === 'string' ? subject.slice(0, 200) : null,
        from: typeof from === 'string' ? from.slice(0, 200) : null,
      },
      binary: { file: item.binary[key] },
    });
  }
}

return out;  // nothing labelled means no items, and the run stops here"""


SUMMARY_CODE = """// Keep a readable line per attachment, and carry the message id through so
// the label can be taken off the ones that made it.
const sent = $('Pick PDF attachments').all();
return $input.all().map((item, i) => {
  const status = item.json.statusCode;
  const body = item.json.body ?? {};
  return {
    json: {
      file_name: sent[i]?.json.file_name,
      message_id: sent[i]?.json.message_id,
      from: sent[i]?.json.from,
      status,
      outcome: status === 200 ? body.status : status === 409 ? 'already processed' : 'failed',
      invoice_id: body.invoice_id ?? null,
    },
  };
});"""


def gmail_request(name: str, position, method: str, url: str, body: str | None = None, **extra) -> dict:
    """HTTP Request node that calls the Gmail API with the n8n Gmail credential."""
    params = {
        "method": method,
        "url": url,
        "authentication": "predefinedCredentialType",
        "nodeCredentialType": "gmailOAuth2",
        "options": {"timeout": 30000},
    }
    if body is not None:
        params.update({"sendBody": True, "specifyBody": "json", "jsonBody": body})
    return node(name, "n8n-nodes-base.httpRequest", 4.2, position, params, **extra)


def build_email_intake_workflow(env: dict) -> dict:
    y, row2 = 300, 480
    x = lambda col: col * 230  # noqa: E731

    nodes = [
        node("Every minute", "n8n-nodes-base.scheduleTrigger", 1.2, (x(0), y), {
            "rule": {"interval": [{"field": "minutes", "minutesInterval": 1}]},
        }),
        node("Config", "n8n-nodes-base.code", 2, (x(1), y), {"jsCode": config_code(env)}),
        gmail_request("Get labels", (x(2), y), "GET", f"{GMAIL_API}/labels"),
        node("Find label", "n8n-nodes-base.code", 2, (x(3), y), {"jsCode": FIND_LABEL_CODE}),
        # n8n's Gmail node is used here for one reason: it decodes the attachments.
        node("Get labelled mail", "n8n-nodes-base.gmail", 2.1, (x(4), y), {
            "resource": "message",
            "operation": "getAll",
            "returnAll": False,
            "limit": MAX_PER_RUN,
            "simple": False,
            "filters": {"q": GMAIL_QUERY},
            "options": {"downloadAttachments": True},
        }, alwaysOutputData=True),
        node("Pick PDF attachments", "n8n-nodes-base.code", 2, (x(5), y), {"jsCode": PICK_PDFS_CODE}),
        node("Send to intake", "n8n-nodes-base.httpRequest", 4.2, (x(6), y), {
            "method": "POST",
            "url": "={{ $('Config').first().json.intake_url }}",
            "sendHeaders": True,
            "headerParameters": {"parameters": [
                {"name": "x-webhook-secret", "value": "={{ $('Config').first().json.webhook_secret }}"},
            ]},
            "sendBody": True,
            "contentType": "multipart-form-data",
            "bodyParameters": {"parameters": [
                {"name": "source", "value": "email"},
                {"parameterType": "formBinaryData", "name": "file", "inputDataFieldName": "file"},
            ]},
            "options": {
                "timeout": 180000,
                "response": {"response": {"fullResponse": True, "neverError": True}},
            },
        # No retryOnFail: n8n runs a node maxTries times even on success, which
        # would post every PDF twice. Retrying is handled better anyway, by
        # leaving the Gmail label on so the next run picks the message up again.
        }, alwaysOutputData=True),
        node("Summarize", "n8n-nodes-base.code", 2, (x(7), y), {"jsCode": SUMMARY_CODE}),
        if_node("Accepted?", (x(8), y),
                "={{ " + json.dumps(ACCEPTED_CODES) + ".includes($json.status) }}",
                {"type": "boolean", "operation": "true", "singleValue": True}),
        # Taking the label off is what stops the message being picked up again.
        # Leaving it on after a failure is deliberate: the next run retries it.
        gmail_request("Take label off", (x(9), y), "POST",
                      f"={GMAIL_API}/messages/{{{{ $json.message_id }}}}/modify",
                      body="={{ JSON.stringify({ removeLabelIds: [$('Find label').first().json.label_id] }) }}",
                      onError="continueRegularOutput"),
        slack_request("Alert team", (x(9), row2), "chat.postMessage",
                      "={{ JSON.stringify({ channel: $('Config').first().json.alerts_channel, "
                      "text: ':warning: An emailed invoice could not be processed: ' + $json.file_name "
                      "+ ' from ' + ($json.from || 'unknown sender') + ' (status ' + $json.status + ')'"
                      " + '. It keeps its label and will be retried.' }) }}",
                      onError="continueRegularOutput"),
    ]

    def link(name: str) -> dict:
        return {"main": [[{"node": name, "type": "main", "index": 0}]]}

    connections = {
        "Every minute": link("Config"),
        "Config": link("Get labels"),
        "Get labels": link("Find label"),
        "Find label": link("Get labelled mail"),
        "Get labelled mail": link("Pick PDF attachments"),
        "Pick PDF attachments": link("Send to intake"),
        "Send to intake": link("Summarize"),
        "Summarize": link("Accepted?"),
        "Accepted?": {"main": [
            [{"node": "Take label off", "type": "main", "index": 0}],
            [{"node": "Alert team", "type": "main", "index": 0}],
        ]},
    }

    return {
        "name": WORKFLOW_NAME,
        "nodes": nodes,
        "connections": connections,
        # It runs every minute and usually finds nothing. Keeping every quiet
        # run would bury the n8n execution list, so only failures are kept.
        "settings": {
            "executionOrder": "v1",
            "saveDataSuccessExecution": "none",
            "saveDataErrorExecution": "all",
        },
    }
