"""n8n workflow 3: "Cleanup".

Every hour, deletes public demo uploads whose 24 hours are up: the stored PDF,
the Slack approval message and the database rows (line items and history go
with them). Built and deployed by scripts/build_n8n_workflow.py.
"""

from __future__ import annotations

import json

from build_n8n_workflow import BUCKET, ROOT, node, slack_request, supabase_request

OUTPUT = ROOT / "n8n" / "workflows" / "invoice-cleanup.json"
WORKFLOW_NAME = "Invoice Processing | 3. Cleanup expired uploads"


def build_cleanup_workflow(env: dict) -> dict:
    y = 300
    x = lambda col: col * 240  # noqa: E731
    settings = {"supabase_url": env["SUPABASE_URL"].rstrip("/"), "bucket": BUCKET}

    nodes = [
        node("Every hour", "n8n-nodes-base.scheduleTrigger", 1.2, (x(0), y), {
            "rule": {"interval": [{"field": "hours", "hoursInterval": 1}]},
        }),
        node("Config", "n8n-nodes-base.code", 2, (x(1), y), {
            "jsCode": "// Generated by scripts/build_n8n_workflow.py.\n"
                      f"return [{{ json: {json.dumps(settings, indent=2)} }}];",
        }),
        # Returns one item per expired upload (none means the workflow simply stops here).
        supabase_request(
            "Find expired uploads", (x(2), y), "GET",
            "/rest/v1/invoices?select=id,file_path,slack_channel,slack_message_ts"
            "&expires_at=lt.{{ new Date().toISOString() }}",
        ),
        slack_request(
            "Delete Slack message", (x(3), y), "chat.delete",
            "={{ JSON.stringify({ channel: $json.slack_channel, ts: $json.slack_message_ts }) }}",
            onError="continueRegularOutput",
        ),
        supabase_request(
            "Delete PDFs", (x(4), y), "DELETE",
            "/storage/v1/object/{{ $('Config').first().json.bucket }}",
            body="={{ JSON.stringify({ prefixes: $('Find expired uploads').all().map(i => i.json.file_path).filter(Boolean) }) }}",
            executeOnce=True, alwaysOutputData=True, onError="continueRegularOutput",
        ),
        supabase_request(
            "Delete invoices", (x(5), y), "DELETE",
            "/rest/v1/invoices?id=in.({{ $('Find expired uploads').all().map(i => i.json.id).join(',') }})",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
    ]

    def link(name: str) -> dict:
        return {"main": [[{"node": name, "type": "main", "index": 0}]]}

    connections = {
        "Every hour": link("Config"),
        "Config": link("Find expired uploads"),
        "Find expired uploads": link("Delete Slack message"),
        "Delete Slack message": link("Delete PDFs"),
        "Delete PDFs": link("Delete invoices"),
    }
    return {"name": WORKFLOW_NAME, "nodes": nodes, "connections": connections, "settings": {"executionOrder": "v1"}}
