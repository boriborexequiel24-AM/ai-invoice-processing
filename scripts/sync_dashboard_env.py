"""Write dashboard/.env.local from the main .env, so keys are only typed once.

Adds IP_HASH_SALT to the main .env first if it's missing.

Usage (from the project root):
    .venv/Scripts/python.exe scripts/sync_dashboard_env.py
"""

from __future__ import annotations

import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAIN_ENV = ROOT / ".env"
DASHBOARD_ENV = ROOT / "dashboard" / ".env.local"

KEYS = [
    "SUPABASE_URL",
    "SUPABASE_ANON_KEY",
    "SUPABASE_SERVICE_ROLE_KEY",
    "N8N_BASE_URL",
    "N8N_WEBHOOK_SECRET",
    "IP_HASH_SALT",
    "DEMO_UPLOADS_PER_IP_PER_DAY",
    "DEMO_MAX_FILE_MB",
    "DEMO_DAILY_UPLOAD_CAP",
]


def read_env(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def main() -> None:
    env = read_env(MAIN_ENV)
    if not env.get("IP_HASH_SALT"):
        with MAIN_ENV.open("a", encoding="utf-8") as f:
            f.write(f"\n# Dashboard: random salt for hashing visitor IPs\nIP_HASH_SALT={secrets.token_urlsafe(32)}\n")
        env = read_env(MAIN_ENV)

    missing = [k for k in KEYS if not env.get(k)]
    if missing:
        raise SystemExit(f"Missing in .env: {', '.join(missing)}")

    lines = ["# Generated by scripts/sync_dashboard_env.py from the main .env. Don't commit."]
    lines += [f"{k}={env[k].rstrip('/') if k.endswith('_URL') else env[k]}" for k in KEYS]
    DASHBOARD_ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {DASHBOARD_ENV.relative_to(ROOT)} ({len(KEYS)} settings)")


if __name__ == "__main__":
    main()
