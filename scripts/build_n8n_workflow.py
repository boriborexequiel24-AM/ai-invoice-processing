"""Build the n8n workflows and deploy them.

1. Intake + Extraction: upload, AI extraction, validation, post to Slack.
   Generated from extraction/prompt.md and extraction/schema.json, the same
   files scripts/eval_extraction.py tests, so n8n always runs the tested prompt.
2. Approval + Xero: Slack button clicks, decision, bill in Xero
   (see scripts/approval_workflow.py).

Output is saved to n8n/workflows/ (with private values replaced) so it is
versioned in git.

Usage (from the project root):
    .venv/Scripts/python.exe scripts/build_n8n_workflow.py            # build the JSON only
    .venv/Scripts/python.exe scripts/build_n8n_workflow.py --deploy   # also create/update them in n8n

Deploying never creates credentials. Pick each credential once on any node in
n8n, then deploy again: it's copied to every node that needs that type.
"""

