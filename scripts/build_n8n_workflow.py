"""Build the n8n "Intake + Extraction" workflow and deploy it.

The workflow is generated from extraction/prompt.md and extraction/schema.json,
the same files scripts/eval_extraction.py tests, so n8n always runs the tested
prompt. Output is saved to n8n/workflows/ so it is versioned in git.

Usage (from the project root):
    .venv/Scripts/python.exe scripts/build_n8n_workflow.py            # build the JSON only
    .venv/Scripts/python.exe scripts/build_n8n_workflow.py --deploy   # also create/update it in n8n

Deploying never touches credentials. After the first deploy, open the
workflow in n8n and pick the credentials on the nodes marked in the docs.
"""

from __future__ import annotations

import argparse
import json
import re
import urllib.error
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPT = (ROOT / "extraction" / "prompt.md").read_text(encoding="utf-8").strip()
SCHEMA = json.loads((ROOT / "extraction" / "schema.json").read_text(encoding="utf-8"))
OUTPUT = ROOT / "n8n" / "workflows" / "invoice-intake-extraction.json"

# Name kept from phase 3 so deploys update the same workflow (it now validates too).
WORKFLOW_NAME = "Invoice Processing | 1. Intake + Extraction"
WEBHOOK_PATH = "invoice-intake"
BUCKET = "invoices"
MAX_UPLOAD_MB = 5
UPLOAD_RETENTION_HOURS = 24

# Chosen in docs/extraction-eval.md. Prices are USD per 1M tokens (input, cached input, output).
MODEL = "gpt-5.4-mini"
REASONING_EFFORT = "low"
MODEL_PRICES = (0.75, 0.075, 4.50)


def load_env() -> dict[str, str]:
    values = {}
    for line in (ROOT / ".env").read_text(encoding="utf-8-sig").splitlines():
        match = re.match(r"^\s*([A-Z0-9_]+)=(.*)$", line)
        if match:
            values[match.group(1)] = match.group(2).strip().strip('"').strip("'")
    return values


# ---------- Node helpers ----------

def node_id(name: str) -> str:
    """Stable IDs so re-deploying doesn't reshuffle the workflow."""
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"invoice-processing/{name}"))


def node(name: str, type_: str, version: float, position: tuple[int, int], parameters: dict, **extra) -> dict:
    return {
        "id": node_id(name),
        "name": name,
        "type": type_,
        "typeVersion": version,
        "position": list(position),
        "parameters": parameters,
        **extra,
    }


def supabase_request(name: str, position, method: str, path: str, body: str | None = None,
                     prefer: str | None = None, **extra) -> dict:
    """HTTP Request node that calls Supabase with the 'Supabase account' credential."""
    headers = [{"name": "Prefer", "value": prefer}] if prefer else []
    params = {
        "method": method,
        "url": "={{ $('Config').first().json.supabase_url }}" + path,
        "authentication": "predefinedCredentialType",
        "nodeCredentialType": "supabaseApi",
        "sendHeaders": bool(headers),
        "headerParameters": {"parameters": headers},
        "options": {},
    }
    if body is not None:
        params.update({"sendBody": True, "specifyBody": "json", "jsonBody": body})
    return node(name, "n8n-nodes-base.httpRequest", 4.2, position, params, **extra)


def respond(name: str, position, code: str | int, body: str) -> dict:
    return node(name, "n8n-nodes-base.respondToWebhook", 1.1, position, {
        "respondWith": "json",
        "responseBody": body,
        "options": {"responseCode": code},
    })


def if_node(name: str, position, left: str, operator: dict) -> dict:
    return node(name, "n8n-nodes-base.if", 2.2, position, {
        "conditions": {
            "options": {"caseSensitive": True, "leftValue": "", "typeValidation": "loose", "version": 2},
            "conditions": [{"id": node_id(name + "/cond"), "leftValue": left, "rightValue": "", "operator": operator}],
            "combinator": "and",
        },
        "options": {},
    })


# ---------- Code node bodies ----------

def config_code(supabase_url: str) -> str:
    return f"""// Settings for this workflow. Generated by scripts/build_n8n_workflow.py.
return [{{
  json: {{
    supabase_url: {json.dumps(supabase_url)},
    bucket: {json.dumps(BUCKET)},
    model: {json.dumps(MODEL)},
    reasoning_effort: {json.dumps(REASONING_EFFORT)},
    price_per_million: {{ input: {MODEL_PRICES[0]}, cached: {MODEL_PRICES[1]}, output: {MODEL_PRICES[2]} }},
    max_upload_mb: {MAX_UPLOAD_MB},
    upload_retention_hours: {UPLOAD_RETENTION_HOURS},
  }},
  binary: $input.first().binary,
}}];"""


VALIDATE_CODE = """// Check the upload is a PDF under the size limit, and keep a base64 copy for the AI call.
const config = $('Config').first().json;
const request = $('Invoice upload').first().json;
const item = $input.first();
const binaryKey = Object.keys(item.binary || {})[0];

const requested = request.body?.source;
const source = ['upload', 'sample', 'email'].includes(requested) ? requested : 'upload';

if (!binaryKey) {
  return [{ json: { valid: false, status: 400, error: 'No file received. Send the PDF as multipart form field "file".' } }];
}

const meta = item.binary[binaryKey];
const buffer = await this.helpers.getBinaryDataBuffer(0, binaryKey);

if (buffer.subarray(0, 5).toString() !== '%PDF-') {
  return [{ json: { valid: false, status: 415, error: 'Only PDF files are accepted.' } }];
}
if (buffer.length > config.max_upload_mb * 1024 * 1024) {
  return [{ json: { valid: false, status: 413, error: `File is larger than ${config.max_upload_mb} MB.` } }];
}

return [{
  json: {
    valid: true,
    source,
    file_name: meta.fileName || 'invoice.pdf',
    size_bytes: buffer.length,
    pdf_base64: buffer.toString('base64'),
  },
  binary: { file: meta },
}];"""


def build_request_code() -> str:
    return f"""// Build the OpenAI request. The prompt and schema come from extraction/ in the repo.
const config = $('Config').first().json;
const upload = $('Validate upload').first().json;

const PROMPT = {json.dumps(PROMPT)};
const SCHEMA = {json.dumps(SCHEMA)};

const body = {{
  model: config.model,
  instructions: PROMPT,
  input: [{{
    role: 'user',
    content: [
      {{ type: 'input_file', filename: upload.file_name, file_data: 'data:application/pdf;base64,' + upload.pdf_base64 }},
      {{ type: 'input_text', text: 'Extract the data from this invoice.' }},
    ],
  }}],
  text: {{ format: {{ type: 'json_schema', name: 'invoice', schema: SCHEMA, strict: true }} }},
  reasoning: {{ effort: config.reasoning_effort }},
}};

return [{{ json: {{ body, started_at: Date.now() }} }}];"""


PARSE_CODE = """// Turn the AI response into database rows. Values are saved exactly as the AI read them;
// checking the math, duplicates and POs happens in the validation step.
const config = $('Config').first().json;
const invoiceId = $('Create invoice row').first().json.id;
const startedAt = $('Build AI request').first().json.started_at;
const response = $input.first().json;

const message = (response.output || []).find(o => o.type === 'message');
const text = message?.content?.find(c => c.type === 'output_text')?.text;
if (!text) throw new Error('AI response had no text output');
const data = JSON.parse(text);

const isoDate = v => (typeof v === 'string' && /^\\d{4}-\\d{2}-\\d{2}$/.test(v) ? v : null);
const currency = v => (typeof v === 'string' && /^[A-Z]{3}$/.test(v.toUpperCase()) ? v.toUpperCase() : null);

const usage = response.usage || {};
const cached = usage.input_tokens_details?.cached_tokens || 0;
const price = config.price_per_million;
const costUsd = ((usage.input_tokens - cached) * price.input + cached * price.cached + usage.output_tokens * price.output) / 1e6;
const minConfidence = Math.min(...Object.values(data.confidence));

return [{
  json: {
    invoice_id: invoiceId,
    patch: {
      status: 'extracted',
      vendor_name_raw: data.vendor_name,
      invoice_number: data.invoice_number,
      invoice_date: isoDate(data.invoice_date),
      due_date: isoDate(data.due_date),
      currency: currency(data.currency),
      subtotal: data.subtotal,
      tax: data.tax,
      total: data.total,
      po_number: data.po_number,
      confidence: data.confidence,
      raw_extraction: data,
    },
    line_items: (data.line_items || []).map((li, i) => ({
      invoice_id: invoiceId,
      position: i + 1,
      description: li.description,
      quantity: li.quantity ?? 1,
      unit_price: li.unit_price,
      amount: li.amount,
    })),
    event: {
      invoice_id: invoiceId,
      step: 'extracted',
      actor: 'ai',
      details: {
        model: config.model,
        seconds: Math.round((Date.now() - startedAt) / 100) / 10,
        input_tokens: usage.input_tokens,
        output_tokens: usage.output_tokens,
        cost_usd: Math.round(costUsd * 1e6) / 1e6,
        min_confidence: minConfidence,
        notes: data.notes,
      },
    },
    min_confidence: minConfidence,
    extracted: data,
  },
}];"""


# ---------- Workflow ----------

def build_workflow(supabase_url: str) -> dict:
    y, row2 = 300, 520
    x = lambda col: 0 + col * 240  # noqa: E731

    nodes = [
        node("Invoice upload", "n8n-nodes-base.webhook", 2, (x(0), y), {
            "httpMethod": "POST",
            "path": WEBHOOK_PATH,
            "authentication": "headerAuth",
            "responseMode": "responseNode",
            "options": {},
        }, webhookId=node_id("webhook")),
        node("Config", "n8n-nodes-base.code", 2, (x(1), y), {"jsCode": config_code(supabase_url)}),
        node("Validate upload", "n8n-nodes-base.code", 2, (x(2), y), {"jsCode": VALIDATE_CODE}),
        if_node("Valid PDF?", (x(3), y), "={{ $json.valid }}",
                {"type": "boolean", "operation": "true", "singleValue": True}),
        respond("Reject upload", (x(4), row2), "={{ $json.status }}", "={{ { error: $json.error } }}"),
        node("Hash file", "n8n-nodes-base.crypto", 1, (x(4), y), {
            "action": "hash",
            "type": "SHA256",
            "binaryData": True,
            "binaryPropertyName": "file",
            "dataPropertyName": "file_hash",
            "encoding": "hex",
        }),
        # The Crypto node returns only JSON, so put the PDF back on the item for the upload.
        node("Reattach file", "n8n-nodes-base.code", 2, (x(5), y - 160), {
            "jsCode": "return [{ json: $input.first().json, binary: $('Validate upload').first().binary }];",
        }),
        node("Store PDF", "n8n-nodes-base.httpRequest", 4.2, (x(5), y), {
            "method": "POST",
            "url": "={{ $('Config').first().json.supabase_url }}/storage/v1/object/"
                   "{{ $('Config').first().json.bucket }}/{{ $json.file_hash }}.pdf",
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "supabaseApi",
            "sendHeaders": True,
            "headerParameters": {"parameters": [
                {"name": "x-upsert", "value": "true"},
                {"name": "Content-Type", "value": "application/pdf"},
            ]},
            "sendBody": True,
            "contentType": "binaryData",
            "inputDataFieldName": "file",
            "options": {},
        }),
        supabase_request(
            "Find existing file", (x(6), y), "GET",
            "/rest/v1/invoices?select=id,status&file_hash=eq.{{ $('Hash file').first().json.file_hash }}",
            alwaysOutputData=True,
        ),
        if_node("Already processed?", (x(7), y), "={{ $json.id }}",
                {"type": "string", "operation": "exists", "singleValue": True}),
        respond("Reply duplicate file", (x(8), row2), 409,
                "={{ { error: 'duplicate_file', message: 'This exact file was already processed.', "
                "invoice_id: $json.id, status: $json.status } }}"),
        supabase_request(
            "Create invoice row", (x(8), y), "POST", "/rest/v1/invoices",
            body="={{ JSON.stringify({\n"
                 "  source: $('Validate upload').first().json.source,\n"
                 "  status: 'extracting',\n"
                 "  file_path: $('Hash file').first().json.file_hash + '.pdf',\n"
                 "  file_hash: $('Hash file').first().json.file_hash,\n"
                 "  file_name: $('Validate upload').first().json.file_name,\n"
                 "  expires_at: $('Validate upload').first().json.source === 'upload'\n"
                 "    ? new Date(Date.now() + $('Config').first().json.upload_retention_hours * 3600 * 1000).toISOString()\n"
                 "    : null\n"
                 "}) }}",
            prefer="return=representation",
        ),
        supabase_request(
            "Log received", (x(9), y), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify({ invoice_id: $('Create invoice row').first().json.id, step: 'received', "
                 "actor: 'system', details: { source: $('Validate upload').first().json.source, "
                 "file_name: $('Validate upload').first().json.file_name, "
                 "size_bytes: $('Validate upload').first().json.size_bytes } }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        node("Build AI request", "n8n-nodes-base.code", 2, (x(10), y), {"jsCode": build_request_code()}),
        node("Extract with AI", "n8n-nodes-base.httpRequest", 4.2, (x(11), y), {
            "method": "POST",
            "url": "https://api.openai.com/v1/responses",
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "openAiApi",
            "sendBody": True,
            "specifyBody": "json",
            "jsonBody": "={{ JSON.stringify($json.body) }}",
            "options": {"timeout": 120000},
        }, retryOnFail=True, maxTries=3, waitBetweenTries=3000, onError="continueErrorOutput"),
        node("Parse AI result", "n8n-nodes-base.code", 2, (x(12), y), {"jsCode": PARSE_CODE},
             onError="continueErrorOutput"),
        supabase_request(
            "Save extraction", (x(13), y), "PATCH",
            "/rest/v1/invoices?id=eq.{{ $json.invoice_id }}",
            body="={{ JSON.stringify($json.patch) }}", prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        supabase_request(
            "Save line items", (x(14), y), "POST", "/rest/v1/invoice_line_items",
            body="={{ JSON.stringify($('Parse AI result').first().json.line_items) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        supabase_request(
            "Log extracted", (x(15), y), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify($('Parse AI result').first().json.event) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        # Phase 4: run the checks in the database (supabase/migrations/*_validate_invoice.sql).
        supabase_request(
            "Validate invoice", (x(16), y), "POST", "/rest/v1/rpc/validate_invoice",
            body="={{ JSON.stringify({ p_invoice_id: $('Parse AI result').first().json.invoice_id }) }}",
            executeOnce=True, onError="continueErrorOutput",
        ),
        respond("Reply processed", (x(17), y), 200,
                "={{ { invoice_id: $json.invoice_id, status: $json.status, flags: $json.flags, "
                "min_confidence: $json.min_confidence, unsure_fields: $json.unsure_fields, "
                "extracted: $('Parse AI result').first().json.extracted } }}"),
        # Error branch: log the error from the failed item first, then mark the invoice failed.
        supabase_request(
            "Log failure", (x(13), row2), "POST", "/rest/v1/invoice_events",
            body="={{ JSON.stringify({ invoice_id: $('Create invoice row').first().json.id, step: 'error', "
                 "actor: 'system', details: { stage: $('Validate invoice').isExecuted ? 'validation' : 'extraction', "
                 "error: String($json.error?.message ?? $json.error ?? 'unknown error').slice(0, 500) } }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        supabase_request(
            "Mark failed", (x(14), row2), "PATCH",
            "/rest/v1/invoices?id=eq.{{ $('Create invoice row').first().json.id }}",
            body="={{ JSON.stringify({ status: 'failed' }) }}",
            prefer="return=minimal", executeOnce=True, alwaysOutputData=True,
        ),
        respond("Reply failed", (x(15), row2), 502,
                "={{ { error: 'processing_failed', invoice_id: $('Create invoice row').first().json.id } }}"),
    ]

    def link(*names: str) -> dict:
        return {"main": [[{"node": n, "type": "main", "index": 0} for n in names]]}

    connections = {
        "Invoice upload": link("Config"),
        "Config": link("Validate upload"),
        "Validate upload": link("Valid PDF?"),
        "Valid PDF?": {"main": [
            [{"node": "Hash file", "type": "main", "index": 0}],
            [{"node": "Reject upload", "type": "main", "index": 0}],
        ]},
        "Hash file": link("Reattach file"),
        "Reattach file": link("Store PDF"),
        "Store PDF": link("Find existing file"),
        "Find existing file": link("Already processed?"),
        "Already processed?": {"main": [
            [{"node": "Reply duplicate file", "type": "main", "index": 0}],
            [{"node": "Create invoice row", "type": "main", "index": 0}],
        ]},
        "Create invoice row": link("Log received"),
        "Log received": link("Build AI request"),
        "Build AI request": link("Extract with AI"),
        "Extract with AI": {"main": [
            [{"node": "Parse AI result", "type": "main", "index": 0}],
            [{"node": "Log failure", "type": "main", "index": 0}],
        ]},
        "Parse AI result": {"main": [
            [{"node": "Save extraction", "type": "main", "index": 0}],
            [{"node": "Log failure", "type": "main", "index": 0}],
        ]},
        "Save extraction": link("Save line items"),
        "Save line items": link("Log extracted"),
        "Log extracted": link("Validate invoice"),
        "Validate invoice": {"main": [
            [{"node": "Reply processed", "type": "main", "index": 0}],
            [{"node": "Log failure", "type": "main", "index": 0}],
        ]},
        "Log failure": link("Mark failed"),
        "Mark failed": link("Reply failed"),
    }

    return {
        "name": WORKFLOW_NAME,
        "nodes": nodes,
        "connections": connections,
        "settings": {"executionOrder": "v1"},
    }


# ---------- n8n API ----------

def n8n_api(env: dict, method: str, path: str, body: dict | None = None) -> dict:
    request = urllib.request.Request(
        env["N8N_BASE_URL"].rstrip("/") + "/api/v1" + path,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"X-N8N-API-KEY": env["N8N_API_KEY"], "Content-Type": "application/json", "Accept": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.loads(response.read() or b"{}")
    except urllib.error.HTTPError as error:
        raise SystemExit(f"n8n API {method} {path} failed: HTTP {error.code} {error.read().decode()[:500]}") from None


def deploy(env: dict, workflow: dict) -> None:
    existing = n8n_api(env, "GET", "/workflows?limit=250")["data"]
    match = next((w for w in existing if w["name"] == workflow["name"]), None)
    if match:
        # Keep credentials already picked in the n8n editor.
        # Keep credentials picked in the n8n editor. A credential picked on one node is
        # copied to every node that uses the same credential type (e.g. all Supabase calls).
        current = n8n_api(env, "GET", f"/workflows/{match['id']}")
        by_type: dict[str, dict] = {}
        for n in current["nodes"]:
            for cred_type, cred in (n.get("credentials") or {}).items():
                by_type.setdefault(cred_type, cred)
        assigned = 0
        for n in workflow["nodes"]:
            params = n["parameters"]
            cred_type = params.get("nodeCredentialType") or (
                "httpHeaderAuth" if params.get("authentication") == "headerAuth" else None)
            if cred_type in by_type:
                n["credentials"] = {cred_type: by_type[cred_type]}
                assigned += 1
        n8n_api(env, "PUT", f"/workflows/{match['id']}", workflow)
        missing = sorted({
            n["name"] for n in workflow["nodes"]
            if (n["parameters"].get("nodeCredentialType") or n["parameters"].get("authentication") == "headerAuth")
            and not n.get("credentials")
        })
        print(f"Updated workflow in n8n (id {match['id']}). Credentials set on {assigned} nodes.")
        if missing:
            print("Still missing credentials: " + ", ".join(missing))
    else:
        created = n8n_api(env, "POST", "/workflows", workflow)
        print(f"Created workflow in n8n (id {created['id']}).")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--deploy", action="store_true", help="create or update the workflow in n8n")
    args = parser.parse_args()

    env = load_env()
    workflow = build_workflow(env["SUPABASE_URL"].rstrip("/"))

    # The repo copy uses a placeholder so the project URL isn't published.
    public = json.loads(json.dumps(workflow).replace(env["SUPABASE_URL"].rstrip("/"), "https://YOUR-PROJECT.supabase.co"))
    OUTPUT.write_text(json.dumps(public, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(workflow['nodes'])} nodes)")

    if args.deploy:
        deploy(env, workflow)


if __name__ == "__main__":
    main()
